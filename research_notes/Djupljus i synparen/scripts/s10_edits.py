"""Write tables/yaml_edits_280.txt: every visual-pair key whose K_deep 0.09 value (step 8) differs from the live
library, old -> new, with a `why` line per pair built from the chain's own numbers (step 1-8 jsons).

Usage: python3 s10_edits.py <repo_root> <scratch_dir with the step jsons> <out_txt>
"""
import json
import os
import sys

import yaml

ROOT = os.path.abspath(sys.argv[1])
S = os.path.abspath(sys.argv[2])
OUT = sys.argv[3]
LIVE = yaml.safe_load(open(os.path.join(ROOT, "fgconfig", "fg_library.yaml")))["interaction_definitions"]
F6, F9 = (json.load(open(os.path.join(S, f"final_{k}.json")))["final"] for k in ("0.06", "0.09"))
R6, R9 = (json.load(open(os.path.join(S, f"rows269_{k}.json")))["rows"] for k in ("0.06", "0.09"))
C6, C9 = (json.load(open(os.path.join(S, f"comb_{k}.json")))["pairs"] for k in ("0.06", "0.09"))
G6, G9 = (json.load(open(os.path.join(S, f"final_{k}.json")))["gate_ling_info"] for k in ("0.06", "0.09"))
KEYS = ("max_intake_rate", "dark_ratio", "stage_access", "depth_access_table")
CLS_ROWS = (0, 1, 3, 5)      # one row per bed class in the 6-row tables (99.9 / 100 / 150 / 250 m)


def num(v):
    """apply_269.py's number format: %g below 1e-3, else repr (so 0 -> 0.0, as the library writes it)."""
    return f"{v:g}" if (v != 0 and abs(v) < 1e-3) else repr(float(v))


WC_LING = {"predatory_fish_preys_on_benthivorous_fish": None, "predatory_fish_preys_on_whiting": "predatory_fish->whiting",
           "predatory_fish_preys_on_planktivorous_fish": "predatory_fish->planktivorous_fish"}


def why(key):
    name = key.replace("_preys_on_", "->")
    a6, a9 = R6[key]["max_intake_rate"], R9[key]["max_intake_rate"]
    parts = [f"measured K_deep 0.09 below 65 m (VOTO gliders; was 0.06 judged) in the section 269 rule-A light:"
             f" 269 a {a6:g} -> {a9:g} (x{a9 / a6:.3f})"]
    if key.endswith("_krill") and key.split("_preys_on_")[0] in ("whiting", "planktivorous_fish", "mackerel"):
        parts.append("2 L cap still binds (rule A = library rule at the same light), the light alone moves it")
    if name in C9:
        c6, c9 = C6[name], C9[name]
        parts.append(f"270 capture p x schooling F re-run on the new R_eff: factor x{c6['factor']:.3f} -> x{c9['factor']:.3f}"
                     f" (F day {c6['F_day']:.3f} -> {c9['F_day']:.3f})")
    if key in WC_LING:
        if WC_LING[key] is None:
            parts.append(f"member corrections (stage p, adult profile, hake out, ling) x{G6['a_mult']:.4f} -> "
                         f"x{G9['a_mult']:.4f}; window re-weighted on the band a's member shares")
        else:
            o6, o9 = G6["other"][WC_LING[key]], G9["other"][WC_LING[key]]
            parts.append(f"ling's activity and window x{o6['a_mult']:.4f} -> x{o9['a_mult']:.4f}")
    t6, t9 = R6[key].get("depth_access_table"), R9[key].get("depth_access_table")
    if t6 and t9:
        c6 = [t6[i]["factor"] for i in CLS_ROWS]
        c9 = [t9[i]["factor"] for i in CLS_ROWS]
        parts.append("classes < 100 / 100-150 / 150-250 / >= 250 m " + " / ".join(f"{x:g}" for x in c6) + " -> "
                     + " / ".join(f"{x:g}" for x in c9))
    parts.append('research_notes/"Djupljus i synparen", "Ljus under 65 m"')
    return "; ".join(parts)


edits = {}
for key, f in F9.items():
    live = LIVE[key]
    ch = {}
    for k in KEYS:
        new, old = f.get(k), live.get(k)
        if new != old:
            ch[k] = (old, new)
    if ch:
        edits[key] = ch


def fmt(v):
    if isinstance(v, list) and v and isinstance(v[0], dict):
        return "\n" + "\n".join(f"      - {{depth_m: {r['depth_m']}, factor: {num(r['factor'])}}}" for r in v)
    if isinstance(v, list):
        return "[" + ", ".join(f"{x:g}" if isinstance(x, float) else str(x) for x in v) + "]"
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


lines = [
    "# Section 280 edits for fgconfig/fg_library.yaml (K_deep 0.06 judged -> 0.09 measured below 65 m in every visual",
    "# pair's derivation; user decision 2026-11-19). Generated by scripts/s10_edits.py from the chain run at",
    "# K_deep 0.09 (scripts/run_chain.sh); the same chain at 0.06 returns the live library (tables/reproduction_0.06.txt).",
    "# Applied as text by scripts/apply_280.py (comments kept). Per pair: the keys to set; '# old:' gives the live value.",
    "# Unchanged visual pairs: WC -> mackerel, mackerel -> planktivores (prey above 65 m), the three benthic pairs.",
    "pairs:",
]
for key, ch in edits.items():
    lines.append(f"  {key}:")
    lines.append("    why: >-")
    import textwrap
    for l in textwrap.wrap(why(key), width=108):
        lines.append(f"      {l}")
    for k, (old, new) in ch.items():
        if k == "depth_access_table":
            lines.append(f"    # old: {k} " + " / ".join(f"{old[i]['factor']:g}" for i in CLS_ROWS))
        else:
            lines.append(f"    # old: {k} {fmt(old)}")
        lines.append(f"    {k}: {fmt(new)}" if k != "depth_access_table" else f"    {k}:{fmt(new)}")
lines += [
    "comment_lines:",
    "  # the section 253 light comment on the five krill pairs states the judged K_deep; it now states the measured one",
    "  - old: \"    # 2-20 m, 0.11 at 20-50 m, 0.091 at 50-65 m, K_deep 0.06 judged; ~x6 the\"",
    "    new:",
    "      - \"    # 2-20 m, 0.11 at 20-50 m, 0.091 at 50-65 m, K_deep 0.06 judged - measured 0.09\"",
    "      - \"    # since section 280 (VOTO gliders, research_notes/\\\"Ljus under 65 m\\\"); ~x6 the\"",
]
open(OUT, "w").write("\n".join(lines) + "\n")
chk = yaml.safe_load(open(OUT))
assert set(chk["pairs"]) == set(edits)
for key, ch in edits.items():
    for k, (old, new) in ch.items():
        assert chk["pairs"][key][k] == new, (key, k, chk["pairs"][key][k], new)
print(f"{len(edits)} pairs, {sum(len(c) for c in edits.values())} keys -> {OUT}")
