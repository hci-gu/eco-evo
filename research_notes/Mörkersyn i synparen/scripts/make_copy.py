"""Library COPY at a new gadoid-eye Ke: the chain's step 8 values at that Ke (K_deep 0.09) with the section 296
factors re-applied on top (one per predator, as live: planktivorous_fish x0.36, whiting and predatory_fish x0.16;
a only), written as text over a copy of the live fgconfig/fg_library.yaml (every comment kept, the apply_280.py
logic). Also writes the edit list: every changed key, old -> new and the ratio, and the band-stage `why`.

Only keys whose value differs from the live library are written. The 296 product is rounded to 10 significant
figures (as the live file stores it: 0.02348 x 0.16 = 0.0037568).

Usage: python3 make_copy.py <repo_root> <final.json at the new Ke> <final.json at Ke 0.02 (the gate run)>
                            <out library.yaml> <out edits.txt> <label>
The target is never the live library: the script refuses a path inside <repo_root>/fgconfig.
"""
import os
import re
import sys
import textwrap

import json
import yaml

ROOT = os.path.abspath(sys.argv[1])
FN = json.load(open(sys.argv[2]))["final"]
F0 = json.load(open(sys.argv[3]))["final"]
OUTLIB = os.path.abspath(sys.argv[4])
OUTED = sys.argv[5]
LABEL = sys.argv[6]
assert not OUTLIB.startswith(os.path.join(ROOT, "fgconfig")), "refusing to write into fgconfig/"
LIVEP = os.path.join(ROOT, "fgconfig", "fg_library.yaml")
LIVE = yaml.safe_load(open(LIVEP, encoding="utf-8-sig"))["interaction_definitions"]
F296 = {"planktivorous_fish": 0.36, "whiting": 0.16, "predatory_fish": 0.16}
KEYS = ("max_intake_rate", "dark_ratio", "stage_access", "depth_access_table")
CLS_ROWS = (0, 1, 3, 5)


def r10(x):
    return float(f"{x:.10g}")


new_vals = {}
for key, f in FN.items():
    pred = key.split("_preys_on_")[0]
    v = dict(f)
    v["max_intake_rate"] = r10(f["max_intake_rate"] * F296.get(pred, 1.0))
    new_vals[key] = v

edits = {}
for key, v in new_vals.items():
    ch = {}
    for k in KEYS:
        new, old = v.get(k), LIVE[key].get(k)
        if new != old:
            ch[k] = (old, new)
    if ch:
        edits[key] = ch


def ratio(old, new):
    return new / old if old else float("nan")


def fmt(v):
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    if isinstance(v, float):
        return f"{v:g}" if (v != 0 and abs(v) < 1e-3) else repr(v)
    return repr(v)


# ------------------------------------------------------------------ edit list
L = [f"# {LABEL}: edits for a COPY of fgconfig/fg_library.yaml. Generated by scripts/make_copy.py from the chain",
     "# (scripts/run_chain_ke.sh) at the new gadoid-eye Ke, K_deep 0.09, x the section 296 factors (planktivorous_fish",
     "# 0.36, whiting and predatory_fish 0.16; a only). The same chain at Ke 0.02 returns the live library exactly",
     "# (tables/reproduction_gate.txt). ratio = new / old.", ""]
L.append(f"{'pair':48s} {'key':20s} {'old':>12s} {'new':>12s} {'ratio':>8s}")
for key, ch in edits.items():
    for k, (old, new) in ch.items():
        if k == "depth_access_table":
            for i in CLS_ROWS:
                o, n = old[i]["factor"], new[i]["factor"]
                L.append(f"{key:48s} {('table ' + format(old[i]['depth_m'], 'g') + ' m'):20s} {o:12.4g} {n:12.4g} "
                         f"{ratio(o, n):8.3f}")
        elif k == "stage_access":
            for i in (0, 1):
                o, n = (old or [None, None])[i], new[i]
                L.append(f"{key:48s} {f'stage_access[{i}]':20s} {o:12.4g} {n:12.4g} {ratio(o, n):8.4f}")
        else:
            L.append(f"{key:48s} {k:20s} {old if old is not None else float('nan'):12.6g} {new:12.6g} "
                     f"{ratio(old, new) if old is not None else float('nan'):8.3f}")
unchanged = [k for k in FN if k not in edits]
L += ["", f"{len(edits)} pairs changed, {sum(len(c) for c in edits.values())} keys; unchanged chain pairs: "
      + ", ".join(unchanged)]
# the a ratio against the chain's own Ke 0.02 value (independent of the 296 rounding)
L += ["", "a ratio new Ke / Ke 0.02 in the chain (before 296):"]
for key in FN:
    L.append(f"  {key:48s} x{FN[key]['max_intake_rate'] / F0[key]['max_intake_rate']:.4f}")
open(OUTED, "w").write("\n".join(L) + "\n")

# ------------------------------------------------------------------ apply to the copy (text, comments kept)
text = open(LIVEP, encoding="utf-8").read()
lines = text.split("\n")


def block(name):
    hits = [n for n, l in enumerate(lines) if l == f"  {name}:"]
    assert len(hits) == 1, (name, hits)
    i = hits[0]
    j = i + 1
    while j < len(lines) and not re.match(r'^  [A-Za-z_]+:$', lines[j]) and not re.match(r'^[A-Za-z_]+:', lines[j]):
        j += 1
    return i, j


for name, ch in edits.items():
    i, j = block(name)
    seg = lines[i:j]
    first = None
    for key, (old, value) in ch.items():
        hit = [n for n, l in enumerate(seg) if l.startswith(f"    {key}:")]
        if key == "depth_access_table":
            assert hit, (name, key)
            n = hit[0]
            m = n + 1
            while m < len(seg) and seg[m].startswith("      -"):
                m += 1
            seg[n + 1:m] = [f"      - {{depth_m: {r['depth_m']}, factor: {fmt(float(r['factor']))}}}" for r in value]
        elif hit:
            seg[hit[0]] = f"    {key}: {fmt(value)}"
            n = hit[0]
        else:
            anchor = [k for k, l in enumerate(seg) if l.startswith("    max_intake_rate:")]
            assert anchor, (name, key)
            n = anchor[0] + 1
            seg.insert(n, f"    {key}: {fmt(value)}")
        first = n if first is None else min(first, n)
    k = first
    while k > 1 and seg[k - 1].startswith("    #"):
        k -= 1
    why = (f"{LABEL}: gadoid-eye Ke 0.02 -> new value in the section 269 rule-A chain (K_deep 0.09), section 296 "
           f"factor re-applied; research_notes/Morkersyn i synparen")
    seg[k:k] = [f"    # {l}" for l in textwrap.wrap(why, width=94)]
    lines[i:j] = seg
os.makedirs(os.path.dirname(OUTLIB), exist_ok=True)
open(OUTLIB, "w", encoding="utf-8").write("\n".join(lines))
# check: the copy parses and carries exactly the new values
chk = yaml.safe_load(open(OUTLIB, encoding="utf-8-sig"))["interaction_definitions"]
for key, v in new_vals.items():
    for k in KEYS:
        assert chk[key].get(k) == v.get(k), (key, k, chk[key].get(k), v.get(k))
print(f"{len(edits)} pairs, {sum(len(c) for c in edits.values())} keys -> {OUTLIB}; edit list {OUTED}")
